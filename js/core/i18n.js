function matchCase(replacement, original){
  if(original===original.toLocaleUpperCase()) return replacement.toLocaleUpperCase();
  if(original===original.toLocaleLowerCase()) return replacement.toLocaleLowerCase();
  if(original && original[0]===original[0].toLocaleUpperCase()) return replacement.charAt(0).toLocaleUpperCase()+replacement.slice(1);
  return replacement;
}
function escapeRegExp(value){return value.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');}
export function translateString(value, language=getLanguage()){
  if(value==null||value==='') return value;
  const input=String(value);
  if(['KKA Teacher Schedule','KKA Schedule','KKA','GSS','WIB','JP 1'].includes(input.trim())) return input;
  const trimmed=input.trim();
  const exact=(language==='en'?exactLower:reverse).get(trimmed.toLocaleLowerCase());
  if(exact!==undefined) return input.replace(trimmed,matchCase(exact,trimmed));
  let output=translateDynamicMessage(input,language);
  // Translate complete phrases first, then a curated list of standalone UI terms.
  for(const entry of DIRECTIONAL_PATTERNS[language==='en'?'en':'id']){
    entry.pattern.lastIndex=0;
    if(!entry.pattern.test(output)) continue;
    entry.pattern.lastIndex=0;
    output=output.replace(entry.pattern,(_match,prefix,found)=>prefix+matchCase(entry.to,found));
  }
  // Translate common variable-rich messages as whole sentences.
  output=translateDynamicMessage(output,language);
  output=translateSafeWords(output,language);
  if(language==='en'){
    output=output.replace(/^(\d+) jadwal dipulihkan dari backup\.$/i,'$1 schedules restored from backup.')
      .replace(/^(\d+) jadwal baru, (\d+) diperbarui, (\d+) duplikat dilewati\.$/i,'$1 new schedules, $2 updated, $3 duplicates skipped.')
      .replace(/^Verifikasi JP 1 tersimpan: (.+)\.$/i,'Period 1 verification saved: $1.')
      .replace(/^Status izin notifikasi: (.+)$/i,'Notification permission status: $1')
      .replace(/^(\d+(?:[.,]\d+)?) MB terpakai dari (\d+) MB$/i,'$1 MB used of $2 MB')
      .replace(/^(\d+) worksheet dianalisis$/i,'$1 worksheets analyzed')
      .replace(/^(\d+)\s+aktivitas tercatat$/i,'$1 activities recorded')
      .replace(/^(\d+)\s+worksheet dianalisis$/i,'$1 worksheets analyzed')
      .replace(/^(\d+)\s+record yang lolos filter awal\.$/i,'$1 records passed the initial filter.')
      .replace(/^(\d+)\s+menit sebelum dimulai$/i,'$1 minutes before start');
  }else{
    output=output.replace(/^(\d+)\s+activities recorded$/i,'$1 aktivitas tercatat')
      .replace(/^(\d+)\s+worksheets analyzed$/i,'$1 worksheet dianalisis')
      .replace(/^(\d+)\s+records passed the initial filter\.$/i,'$1 record yang lolos filter awal.')
      .replace(/^(\d+)\s+minutes before start$/i,'$1 menit sebelum dimulai');
  }
  return output;
}

function translateTextNode(node,language){
  let record=originalText.get(node);
  if(!record){record={source:node.nodeValue,last:node.nodeValue};originalText.set(node,record);}
  else if(node.nodeValue!==record.last){record.source=node.nodeValue;}
  const next=translateString(record.source,language);
  if(node.nodeValue!==next) node.nodeValue=next;
  record.last=next;
}
function translateElementAttributes(el,language){
  const attrs=['placeholder','title','aria-label','aria-description','aria-valuetext','alt','data-tooltip'];
  if(el instanceof HTMLInputElement && ['button','submit','reset'].includes(el.type)) attrs.push('value');
  let originals=originalAttributes.get(el);
  if(!originals){originals={};originalAttributes.set(el,originals);}
  for(const attr of attrs){
    if(!el.hasAttribute(attr)) continue;
    const current=el.getAttribute(attr);
    if(!originals[attr]) originals[attr]={source:current,last:current};
    else if(current!==originals[attr].last) originals[attr].source=current;
    const next=translateString(originals[attr].source,language);
    if(current!==next) el.setAttribute(attr,next);
    originals[attr].last=next;
  }
}
function translateSubtree(root,language){
  if(!root) return;
  if(root.nodeType===Node.TEXT_NODE){const parent=root.parentElement;if(parent?.closest?.('[data-no-translate],[contenteditable="true"]')||['SCRIPT','STYLE','NOSCRIPT','TEXTAREA','CODE','PRE'].includes(parent?.tagName))return;translateTextNode(root,language);return;}
  if(root.nodeType===Node.ELEMENT_NODE){
    if(root.closest?.('[data-no-translate],[contenteditable="true"]') || ['SCRIPT','STYLE','NOSCRIPT','CODE','PRE'].includes(root.tagName)) return;
    translateElementAttributes(root,language);
  }
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT,{acceptNode(node){
    const p=node.parentElement;
    if(!p||p.closest?.('[data-no-translate],[contenteditable="true"]')||['SCRIPT','STYLE','NOSCRIPT','TEXTAREA','CODE','PRE'].includes(p.tagName)) return NodeFilter.FILTER_REJECT;
    if(!node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
    return NodeFilter.FILTER_ACCEPT;
  }});
  // Translate while walking instead of allocating a temporary array for every subtree.
  while(walker.nextNode()) translateTextNode(walker.currentNode,language);
  if(root.querySelectorAll) root.querySelectorAll('[placeholder],[title],[aria-label],[aria-description],[aria-valuetext],[alt],[data-tooltip],input[type=button],input[type=submit],input[type=reset]').forEach(el=>translateElementAttributes(el,language));
}
export function applyTranslations(root=document){translateSubtree(root,getLanguage());}
